/**
 * Índice de búsqueda de POIs con el texto ya normalizado.
 * Se construye una sola vez por proceso: antes cada búsqueda normalizaba
 * nombre + comuna + etiquetas de todos los POIs (cientos de `normalize('NFD')`
 * por pulsación de tecla).
 */
interface PoiSearchEntry {
  poi: PointOfInterest;
  name: string;
  commune: string;
  tags: string;
}

let poiSearchIndex: PoiSearchEntry[] | null = null;

function getPoiSearchIndex(): PoiSearchEntry[] {
  if (!poiSearchIndex) {
    poiSearchIndex = CHILE_POIS.map((poi) => ({
      poi,
      name: normalizeForSearch(poi.name),
      commune: normalizeForSearch(poi.commune),
      tags: normalizeForSearch(poi.tags.join(' ')),
    }));
  }
  return poiSearchIndex;
}

/**
 * Busca Puntos de Interés (POIs) por coincidencia de texto (nombre, etiquetas, comuna).
 */
export function searchPOIs(query: string, maxResults: number = 8): PointOfInterest[] {
  const normQuery = normalizeForSearch(query.trim());
  if (normQuery.length < 2) return [];

  const terms = normQuery.split(/\s+/).filter(Boolean);
  const scored: { poi: PointOfInterest; score: number }[] = [];

  for (const entry of getPoiSearchIndex()) {
    let score = 0;

    // Coincidencia de nombre completo
    if (entry.name === normQuery) score += 100;
    else if (entry.name.startsWith(normQuery)) score += 50;
    else if (entry.name.includes(normQuery)) score += 30;

    // Coincidencia de términos
    for (const term of terms) {
      if (entry.name.includes(term)) score += 15;
      if (entry.commune.includes(term)) score += 10;
      if (entry.tags.includes(term)) score += 8;
    }

    if (score > 0) scored.push({ poi: entry.poi, score });
  }

  return scored
    .sort((a, b) => b.score - a.score)
    .slice(0, maxResults)
    .map((item) => item.poi);
}
